"""Index existing artifacts and export observed CSV summaries; never fills missing results."""
from __future__ import annotations
import html
from datetime import datetime, timezone
from pathlib import Path
import uuid
from .common import save_csv, save_json
from .runtime import file_hash


def build_report(cfg):
    out=cfg.exp_dir/'reports'/(datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+uuid.uuid4().hex[:8])
    out.mkdir(parents=True)
    rows=[]
    for p in sorted(cfg.exp_dir.rglob('*')):
        if not p.is_file() or 'reports' in p.relative_to(cfg.exp_dir).parts:continue
        if p.suffix.lower() not in ('.csv','.json','.jsonl','.png','.pdf','.svg','.log','.pt','.safetensors'):continue
        rows.append({'path':str(p.relative_to(cfg.exp_dir)),'bytes':p.stat().st_size,'type':p.suffix})
    save_csv(rows,out/'artifact_index.csv')
    # Plain filesystem links work in a local browser. Large binary artifacts are indexed, not copied.
    import os
    links=[]
    for r in rows:
        path=cfg.exp_dir/r['path'];url=os.path.relpath(path,out)
        links.append('<tr><td><a href="'+html.escape(url,quote=True)+'">'+html.escape(r['path'])+'</a></td><td>'+str(r['bytes'])+'</td></tr>')
    role = cfg.runtime.study_role
    (out/'index.html').write_text('<!doctype html><meta charset="utf-8"><title>Experiment artifacts</title>'
      '<h1>Recorded experiment artifacts — '+html.escape(role)+'</h1><p>Calibration outputs are exploratory, not confirmatory evidence.</p><p>Missing stages are not inferred. Development and test results remain separate.</p>'
      '<table><tr><th>Path</th><th>Bytes</th></tr>'+''.join(links)+'</table>',encoding='utf-8')
    import pandas as pd
    for r in rows:
        p=cfg.exp_dir/r['path']
        if p.suffix!='.csv' or not any(x in p.stem for x in ('summary','effects','detection','means','quality','training_profile')):continue
        try:df=pd.read_csv(p)
        except pd.errors.EmptyDataError:continue
        if not len(df) or 'status' in df.columns:continue
        name='__'.join(Path(r['path']).parts).replace('.csv','.tex')
        (out/name).write_text(df.to_latex(index=False,escape=True,float_format=lambda v:f'{v:.6g}'),encoding='utf-8')
    save_json({'project':str(cfg.exp_dir),'study_role':role,'config':cfg.fingerprint(),'n_artifacts':len(rows),
               'source':'observed files only; no experimental estimates were generated by reporting'},out/'manifest.json')
    return out/'index.html'
